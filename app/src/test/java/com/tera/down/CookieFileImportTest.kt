    // --- Parser Tests ---

    @Test
    fun parse_netscapeFormat_parsesStandardAndHttpOnlyCookies() {
        val netscapeContent = """
            # Netscape HTTP Cookie File
            # http://curl.haxx.se/rfc/cookie_spec.html
            # This file was generated by EditThisCookie

            .terabox.com	TRUE	/	TRUE	1893456000	browserid	abc123xyz
            #HttpOnly_.terabox.com	TRUE	/	TRUE	1893456000	ndus	AUTH_TOKEN_VALUE
            www.terabox.com	FALSE	/share	FALSE	1893456000	panweb	1
        """.trimIndent()

        val result = CookieFileParser.parse(netscapeContent)
        assertTrue(result is CookieFileParseResult.Success)
        val success = result as CookieFileParseResult.Success
        assertEquals(CookieFileFormat.NETSCAPE, success.format)
        assertEquals(3, success.cookies.size)

        val browserid = success.cookies[0]
        assertEquals("browserid", browserid.name)
        assertEquals("abc123xyz", browserid.value)
        assertEquals(".terabox.com", browserid.domain)
        assertFalse(browserid.isHttpOnly)
        assertTrue(browserid.isSecure)

        val ndus = success.cookies[1]
        assertEquals("ndus", ndus.name)
        assertEquals("AUTH_TOKEN_VALUE", ndus.value)
        assertEquals(".terabox.com", ndus.domain)
        assertTrue(ndus.isHttpOnly)
        assertTrue(ndus.isSecure)

        val panweb = success.cookies[2]
        assertEquals("panweb", panweb.name)
        assertEquals("1", panweb.value)
        assertEquals("www.terabox.com", panweb.domain)
    }

