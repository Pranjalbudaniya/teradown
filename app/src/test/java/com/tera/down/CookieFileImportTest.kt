    @Test
    fun import_serverValidationFails_rejectedSafely() = runTest(testDispatcher) {
        val validNetscape = """
            .terabox.com	TRUE	/	TRUE	1893456000	ndus	VALID_STRUCT_TOKEN
        """.trimIndent()

        val failingValidator = object : SessionValidator {
            override suspend fun validateSession(session: TeraboxSession): SessionValidationResult =
                SessionValidationResult.NotLoggedIn("Session token was revoked by user or expired.")
        }
        val importer = CookieFileImporter(sessionRepository, failingValidator)

        val result = importer.importFromText(validNetscape)
        assertTrue(result is CookieImportResult.RejectedSession)
        val rejected = result as CookieImportResult.RejectedSession
        assertTrue(rejected.reason.contains("revoked", ignoreCase = true))
        assertNull(sessionRepository.getSession())
    }

    @Test
    fun import_serverNetworkFailure_distinguishedFromRejection() = runTest(testDispatcher) {
        val validNetscape = """
            .terabox.com	TRUE	/	TRUE	1893456000	ndus	VALID_STRUCT_TOKEN
        """.trimIndent()

        val networkFailingValidator = object : SessionValidator {
            override suspend fun validateSession(session: TeraboxSession): SessionValidationResult =
                SessionValidationResult.NetworkError("ConnectException connection refused")
        }
        val importer = CookieFileImporter(sessionRepository, networkFailingValidator)

        val result = importer.importFromText(validNetscape)
        assertTrue(result is CookieImportResult.NetworkFailure)
        val netErr = result as CookieImportResult.NetworkFailure
        assertTrue(netErr.reason.contains("Network error", ignoreCase = true))
        assertNull(sessionRepository.getSession())
    }

    @Test
    fun import_successfulImport_validatesAndPersistsSession() = runTest(testDispatcher) {
        mockWebServer.enqueue(
            MockResponse()
                .setResponseCode(200)
                .setHeader("Content-Type", "application/json")
                .setBody("""{"errno": 0, "data": {"uk": 789012, "uname": "cookie_importer_user"}}""")
        )

        val validator = DefaultSessionValidator(
            httpClient = testHttpClient,
            baseUrlOverride = mockWebServer.url("/").toString()
        )
        val importer = CookieFileImporter(sessionRepository, validator)

        val validNetscape = """
            #HttpOnly_.terabox.com	TRUE	/	TRUE	1893456000	ndus	IMPORTED_NDUS_TOKEN
            .terabox.com	TRUE	/	TRUE	1893456000	panweb	1
        """.trimIndent()

        val result = importer.importFromText(validNetscape)
        assertTrue(result is CookieImportResult.Success)
        val success = result as CookieImportResult.Success
        assertEquals("terabox.com", success.domain)
        assertEquals(2, success.cookieCount)

        // Session was persisted in repository
        val session = sessionRepository.getSession()
        assertNotNull(session)
        assertTrue(session!!.cookieString.contains("ndus=IMPORTED_NDUS_TOKEN"))
        assertTrue(session.cookieString.contains("panweb=1"))
    }

    // --- SettingsViewModel Integration Tests ---

    @Test
    fun settingsViewModel_importCookieFile_updatesStateAndPersists() = runTest(testDispatcher) {
        mockWebServer.enqueue(
            MockResponse()
                .setResponseCode(200)
                .setHeader("Content-Type", "application/json")
                .setBody("""{"errno": 0, "data": {"uk": 12345}}""")
        )

        val validator = DefaultSessionValidator(
            httpClient = testHttpClient,
            baseUrlOverride = mockWebServer.url("/").toString()
        )
        val importer = CookieFileImporter(sessionRepository, validator)
        val storageManager = StorageManager(baseDir = tempRoot)
        val settingsRepo = FakeSettingsRepository()
        val connectivityMonitor = FakeNetworkConnectivityMonitor(initialConnected = true, initialWifi = true)

        val viewModel = SettingsViewModel(
            settingsRepository = settingsRepo,
            storageManager = storageManager,
            networkConnectivityMonitor = connectivityMonitor,
            sessionRepository = sessionRepository,
            sessionValidator = validator,
            cookieFileImporter = importer
        )

        assertFalse(viewModel.uiState.value.isSessionActive)

        val cookieContent = """
            .terabox.com	TRUE	/	TRUE	1893456000	ndus	UI_TEST_TOKEN
            .terabox.com	TRUE	/	TRUE	1893456000	panweb	1
        """.trimIndent()

        viewModel.importCookieFileContent(cookieContent)

        val state = viewModel.uiState.value
        assertTrue(state.isSessionActive)
        assertEquals("terabox.com", state.activeSessionDomain)
        assertNotNull(state.cookieImportMessage)
        assertTrue(state.cookieImportMessage!!.contains("verified successfully", ignoreCase = true))
        assertNull(state.cookieImportError)

        // Verify logout clears state
        viewModel.logout()
        assertFalse(viewModel.uiState.value.isSessionActive)
        assertNull(sessionRepository.getSession())
    }

    // --- Queue & Manifest Preservation Test ---

    @Test
    fun queueAndManifest_preservedAcrossCookieImportAndLogout() = runTest(testDispatcher) {
        val fakeTaskDao = FakeDownloadTaskDao()
        val fakeMediaDao = FakeLibraryMediaDao()
        val fakeManifestDao = FakeDownloadManifestDao()

        val manifestRepo = ManifestRepositoryImpl(
            downloadManifestDao = fakeManifestDao,
            ioDispatcher = testDispatcher
        )
        val queueRepo = DownloadQueueRepositoryImpl(
            downloadTaskDao = fakeTaskDao,
            libraryMediaDao = fakeMediaDao,
            manifestReporter = manifestRepo,
            ioDispatcher = testDispatcher
        )

        // 1. Enqueue download tasks
        val files = listOf(
            com.tera.down.core.model.ShareFileItem(
                fsId = "1001",
                name = "video1.mp4",
                size = 1048576L,
                relPath = "video1.mp4",
                mediaType = MediaType.VIDEO,
                category = 1
            ),
            com.tera.down.core.model.ShareFileItem(
                fsId = "1002",
                name = "photo.jpg",
                size = 204800L,
                relPath = "photo.jpg",
                mediaType = MediaType.PHOTO,
                category = 3
            )
        )

        val taskIds = queueRepo.enqueueShareFiles(
            surl = "testSurl",
            originalUrl = "https://terabox.com/s/1abc",
            items = files
        )
        assertEquals(2, taskIds.size)

        // Queue has 2 queued tasks
        var tasks = queueRepo.observeAllTasks().first()
        assertEquals(2, tasks.size)
        assertEquals(DownloadStatus.QUEUED, tasks[0].status)
        assertEquals(DownloadStatus.QUEUED, tasks[1].status)

        // 2. Perform cookie import via SettingsViewModel
        val fakeValidator = object : SessionValidator {
            override suspend fun validateSession(session: TeraboxSession): SessionValidationResult =
                SessionValidationResult.Valid(verifiedDomain = "www.terabox.app")
        }
        val importer = CookieFileImporter(sessionRepository, fakeValidator)
        val storageManager = StorageManager(baseDir = tempRoot)
        val settingsRepo = FakeSettingsRepository()
        val connectivityMonitor = FakeNetworkConnectivityMonitor(initialConnected = true, initialWifi = true)

        val viewModel = SettingsViewModel(
            settingsRepository = settingsRepo,
            storageManager = storageManager,
            networkConnectivityMonitor = connectivityMonitor,
            sessionRepository = sessionRepository,
            sessionValidator = fakeValidator,
            cookieFileImporter = importer
        )

        viewModel.importCookieFileContent(".terabox.com\tTRUE\t/\tTRUE\t1893456000\tndus\tTEST_TOKEN")
        assertTrue(viewModel.uiState.value.isSessionActive)

        // Verify queue and manifests are completely preserved
        tasks = queueRepo.observeAllTasks().first()
        assertEquals(2, tasks.size)
        assertEquals(taskIds.toSet(), tasks.map { it.id }.toSet())
        var manifests = manifestRepo.observeAllManifest().first()
        assertEquals(2, manifests.size)

        // 3. Perform logout
        viewModel.logout()
        assertFalse(viewModel.uiState.value.isSessionActive)

        // Verify queue and manifests STILL remain preserved
        tasks = queueRepo.observeAllTasks().first()
        assertEquals(2, tasks.size)
        assertEquals(taskIds.toSet(), tasks.map { it.id }.toSet())
        manifests = manifestRepo.observeAllManifest().first()
        assertEquals(2, manifests.size)
    }
