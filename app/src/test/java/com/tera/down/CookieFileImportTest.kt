    // --- Importer Security & Validation Tests ---

    @Test
    fun import_irrelevantDomains_rejectedSafely() = runTest(testDispatcher) {
        val nonTeraboxNetscape = """
            .google.com	TRUE	/	TRUE	1893456000	SID	GOOGLE_TOKEN
            .facebook.com	TRUE	/	TRUE	1893456000	c_user	FB_TOKEN
            .malicious.com	TRUE	/	TRUE	1893456000	ndus	FAKE_NDUS_ON_EVIL_SITE
        """.trimIndent()

        val fakeValidator = object : SessionValidator {
            override suspend fun validateSession(session: TeraboxSession): SessionValidationResult =
                SessionValidationResult.Valid(verifiedDomain = "www.terabox.app")
        }
        val importer = CookieFileImporter(sessionRepository, fakeValidator)

        val result = importer.importFromText(nonTeraboxNetscape)
        assertTrue(result is CookieImportResult.IrrelevantDomains)
        assertNull(sessionRepository.getSession())
    }

